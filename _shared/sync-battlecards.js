/* sync-battlecards.js
   Single-source battlecards. Reads the canonical COMPETITORS from
   Competitive Battlecards/index.html and writes a self-contained, data-driven
   battlecards module to _shared/generated/battlecards-module.js.

   The module: injects its own content CSS, exposes window.ottBc* handlers, and
   renderBattlecards(mountId) builds the grid + modals from BATTLECARDS_DATA
   using each dashboard's existing .bc-* visual styling. Re-run whenever the
   canonical battlecards change, then re-sync into the dashboards.

   Run:  node _shared/sync-battlecards.js
*/
const fs = require('fs');
const path = require('path');
const CANON = 'C:/Users/blfri/Documents/Claude/Projects/Competitive Battlecards/index.html';
const OUT_DIR = path.join(__dirname, 'generated');
const h = fs.readFileSync(CANON, 'utf8');

// ---- 1. Extract COMPETITORS object literal (brace-matched, string-aware) ----
const start = h.indexOf('const COMPETITORS = {');
let i = h.indexOf('{', start), depth = 0, end = -1, inStr = null;
for (; i < h.length; i++){
  const c = h[i], p = h[i-1];
  if (inStr){ if (c === inStr && p !== '\\') inStr = null; continue; }
  if (c === '"' || c === "'" || c === '`'){ inStr = c; continue; }
  if (c === '{') depth++; else if (c === '}'){ depth--; if (depth === 0){ end = i; break; } }
}
const COMPETITORS = eval('(' + h.slice(h.indexOf('{', start), end + 1) + ')');

// ---- 2. Grid order + per-slug tags ----
const gridRe = /<div class="card"\s+data-threat="([^"]+)"\s+data-tags="([^"]*)"\s+onclick="openModal\('([^']+)'\)"/g;
const tags = {}; const order = []; let m;
while ((m = gridRe.exec(h))){ tags[m[3]] = m[2]; order.push(m[3]); }

// ---- 3. Build the dashboard data model (threat lowercased; 4 content panels) ----
const DATA = {};
for (const slug of order){
  const c = COMPETITORS[slug];
  DATA[slug] = {
    name: c.name,
    tagline: c.tagline,
    threat: String(c.threat).toLowerCase(),   // high | medium | low
    tags: (tags[slug] || '').split(/\s+/).filter(Boolean).slice(0,4).map(w=>w.replace(/\b\w/g,x=>x.toUpperCase())).join(' · '),
    pitch: c.pitch,
    weaknesses: c.weaknesses,
    winmoves: c.winmoves,
    gaps: c.gaps
  };
}

// ---- 4. Namespaced content CSS (so canonical .their-edge/.weakness-item/etc. render
//         inside .bc-modal-body, plus a green style for the standardized 'low' threat) ----
const P = '.bc-modal-body', Q = '.bc-print-card';   // canonical content classes render in both modal + print
const CONTENT_CSS = `
/* content classes used by canonical field HTML, scoped to battlecard modal + print */
${P} .section-label,${Q} .section-label{font-size:0.7rem;font-weight:800;letter-spacing:0.6px;text-transform:uppercase;color:var(--accent);margin:0.85rem 0 0.4rem;}
${P} .section-label:first-child,${Q} .section-label:first-child{margin-top:0;}
${P} .their-edge,${Q} .their-edge{font-size:0.86rem;line-height:1.55;color:var(--gray5);margin-bottom:0.5rem;}
${P} .weakness-item,${P} .loss-item,${P} .win-move,${P} .overcome-item,${P} .gap-item,${Q} .weakness-item,${Q} .loss-item,${Q} .win-move,${Q} .overcome-item,${Q} .gap-item{font-size:0.86rem;line-height:1.5;color:var(--gray5);margin-bottom:0.45rem;display:flex;gap:0.5rem;}
${P} .wi-icon,${P} .loss-icon,${Q} .wi-icon,${Q} .loss-icon{flex-shrink:0;}
${P} .gap-item,${Q} .gap-item{flex-direction:column;gap:0.15rem;}
${P} .gap-label,${Q} .gap-label{font-weight:700;color:var(--navy);font-size:0.82rem;}
${P} .killer-quote,${Q} .killer-quote{background:var(--accent-light);border-left:3px solid var(--accent);border-radius:6px;padding:0.6rem 0.8rem;margin:0.5rem 0 0.75rem;font-size:0.85rem;color:var(--navy);font-style:italic;}
${P} .killer-quote-label,${Q} .killer-quote-label{display:block;font-style:normal;font-weight:800;font-size:0.66rem;letter-spacing:0.5px;text-transform:uppercase;color:var(--accent);margin-bottom:0.2rem;}
/* standardized 'low' threat bucket (green) — mirrors the old 'easy' bucket */
.bc-tile-threat.low{color:#27ae60;}
.bc-filter.low.active,.bc-filter.low{border-color:#27ae60;}
.bc-filter.low.active{background:#27ae60;color:#fff;}
`.trim();

// ---- 5. The module (fixed render + handlers; only DATA/CSS are generated) ----
const THREAT_LABEL = { high:'🔴 High Threat', medium:'🟡 Medium Threat', low:'🟢 Lower Threat' };
const moduleText = `/* OTT-BATTLECARDS:START — generated by _shared/sync-battlecards.js from Competitive Battlecards/index.html. Do not hand-edit; edit the canonical + re-sync. */
const BATTLECARDS_DATA = ${JSON.stringify(DATA)};
const BATTLECARDS_CSS = ${JSON.stringify(CONTENT_CSS)};
const BC_THREAT_LABEL = ${JSON.stringify(THREAT_LABEL)};
function renderBattlecards(mountId){
  const mount = document.getElementById(mountId); if(!mount) return;
  if(!document.getElementById('ott-bc-css')){ const st=document.createElement('style'); st.id='ott-bc-css'; st.textContent=BATTLECARDS_CSS; document.head.appendChild(st); }
  const slugs = Object.keys(BATTLECARDS_DATA);
  const counts = {all:slugs.length, high:0, medium:0, low:0}; slugs.forEach(s=>counts[BATTLECARDS_DATA[s].threat]++);
  const filters = '<div class="bc-filters">'
    + '<button class="bc-filter active" onclick="ottBcFilter(\\'all\\',this)">All '+counts.all+'</button>'
    + '<button class="bc-filter high" onclick="ottBcFilter(\\'high\\',this)">🔴 High ('+counts.high+')</button>'
    + '<button class="bc-filter medium" onclick="ottBcFilter(\\'medium\\',this)">🟡 Medium ('+counts.medium+')</button>'
    + '<button class="bc-filter low" onclick="ottBcFilter(\\'low\\',this)">🟢 Lower ('+counts.low+')</button></div>';
  const tiles = slugs.map(s=>{ const c=BATTLECARDS_DATA[s];
    return '<div class="bc-tile" data-threat="'+c.threat+'" onclick="ottBcOpen(\\''+s+'\\')">'
      + '<div class="bc-tile-threat '+c.threat+'">'+BC_THREAT_LABEL[c.threat]+'</div>'
      + '<div class="bc-tile-name">'+c.name+'</div>'
      + '<div class="bc-tile-tagline">'+c.tagline+'</div>'
      + (c.tags?'<div class="bc-tile-tags">'+c.tags+'</div>':'')
      + '<div class="bc-tile-cta">View Details ›</div></div>';
  }).join('');
  const modals = slugs.map(s=>{ const c=BATTLECARDS_DATA[s];
    return '<div class="bc-modal-overlay" id="ott-bcm-'+s+'" onclick="ottBcClose(event,this)"><div class="bc-modal">'
      + '<div class="bc-modal-hdr"><div><h3>'+c.name+'</h3><p>'+c.tagline+'</p></div><button class="bc-modal-close" onclick="ottBcCloseById(\\'ott-bcm-'+s+'\\')">✕</button></div>'
      + '<div class="bc-modal-tabs">'
      +   '<button class="bc-mtab active" onclick="ottBcTab(this,\\'ott-p-'+s+'\\')">Their Pitch</button>'
      +   '<button class="bc-mtab" onclick="ottBcTab(this,\\'ott-w-'+s+'\\')">VoC Weaknesses</button>'
      +   '<button class="bc-mtab" onclick="ottBcTab(this,\\'ott-m-'+s+'\\')">Win Moves</button>'
      +   '<button class="bc-mtab" onclick="ottBcTab(this,\\'ott-g-'+s+'\\')">⚠ Our Gaps</button></div>'
      + '<div class="bc-modal-body">'
      +   '<div class="bc-mpanel active" id="ott-p-'+s+'">'+c.pitch+'</div>'
      +   '<div class="bc-mpanel" id="ott-w-'+s+'">'+c.weaknesses+'</div>'
      +   '<div class="bc-mpanel" id="ott-m-'+s+'">'+c.winmoves+'</div>'
      +   '<div class="bc-mpanel" id="ott-g-'+s+'">'+c.gaps+'</div>'
      + '</div></div></div>';
  }).join('');
  const TC = { high:'#E74C3C', medium:'#F39C12', low:'#27AE60' };
  const printCards = slugs.map(s=>{ const c=BATTLECARDS_DATA[s]; const col=TC[c.threat];
    return '<div class="bc-print-card" style="border-left:4px solid '+col+';">'
      + '<div style="display:flex;justify-content:space-between;align-items:baseline;margin-bottom:0.35rem;"><h4>'+c.name+'</h4><span style="font-size:0.72rem;color:'+col+';font-weight:700;">'+BC_THREAT_LABEL[c.threat]+'</span></div>'
      + '<p style="font-size:0.8rem;color:#555;margin-bottom:0.4rem;">'+c.tagline+(c.tags?' · '+c.tags:'')+'</p>'
      + c.pitch + c.weaknesses + c.winmoves + c.gaps + '</div>';
  }).join('');
  const printSection = '<div class="bc-print-section" id="ott-bc-print" style="display:none;"><div class="card" style="margin-bottom:0.75rem;"><div class="card-title" style="margin-bottom:0.5rem;">⚔️ Competitive Battlecard Reference — All '+slugs.length+' Competitors</div><p style="font-size:0.82rem;color:#666;margin-bottom:0.75rem;font-style:italic;">Internal use only. Verify before using in customer conversations.</p><div class="bc-print-grid">'+printCards+'</div></div></div>';
  // drop any stale hand-maintained print sections elsewhere on the page, then render ours
  document.querySelectorAll('.bc-print-section').forEach(n=>{ if(n.id!=='ott-bc-print' && !mount.contains(n)) n.remove(); });
  mount.innerHTML = filters + '<div class="bc-grid">'+tiles+'</div>' + modals + printSection;
}
window.ottBcOpen=function(s){ const el=document.getElementById('ott-bcm-'+s); if(el) el.classList.add('bc-open'); };
window.ottBcClose=function(e,el){ if(e.target===el) el.classList.remove('bc-open'); };
window.ottBcCloseById=function(id){ const el=document.getElementById(id); if(el) el.classList.remove('bc-open'); };
window.ottBcTab=function(btn,pid){ const modal=btn.closest('.bc-modal'); modal.querySelectorAll('.bc-mtab').forEach(b=>b.classList.remove('active')); btn.classList.add('active'); modal.querySelectorAll('.bc-mpanel').forEach(p=>p.classList.remove('active')); const pl=document.getElementById(pid); if(pl) pl.classList.add('active'); };
window.ottBcFilter=function(threat,btn){ document.querySelectorAll('.bc-filter').forEach(b=>b.classList.remove('active')); btn.classList.add('active'); document.querySelectorAll('.bc-tile').forEach(t=>{ t.style.display=(threat==='all'||t.dataset.threat===threat)?'':'none'; }); };
document.addEventListener('keydown',function(e){ if(e.key==='Escape') document.querySelectorAll('.bc-modal-overlay.bc-open').forEach(el=>el.classList.remove('bc-open')); });
/* render the battlecards whenever the Battlecards reference tab is shown (works across all dashboards) */
if (typeof switchRefTab === 'function' && !window.__bcRefWrap){ window.__bcRefWrap = true; const _swr = switchRefTab; window.switchRefTab = function(btn, pid){ _swr(btn, pid); if (pid === 'ref-battlecards') renderBattlecards('bc-mount'); }; }
/* OTT-BATTLECARDS:END */`;

fs.mkdirSync(OUT_DIR, { recursive: true });
const outFile = path.join(OUT_DIR, 'battlecards-module.js');
fs.writeFileSync(outFile, moduleText);
console.log('Wrote ' + outFile);
console.log('Competitors: ' + order.length + '  (high '+Object.values(DATA).filter(d=>d.threat==='high').length+', medium '+Object.values(DATA).filter(d=>d.threat==='medium').length+', low '+Object.values(DATA).filter(d=>d.threat==='low').length+')');
console.log('Module size: ' + (moduleText.length/1024).toFixed(1) + ' KB');
